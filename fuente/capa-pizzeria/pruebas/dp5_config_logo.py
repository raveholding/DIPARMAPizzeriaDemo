# Acceso oculto (doble clic / doble toque en el logo de la carta) y Configuración dinámica (secciones, buscador, sin guardar).
from playwright.sync_api import sync_playwright
B='http://127.0.0.1:8765/';errs=[]
def ok(c,m):print(('OK   ' if c else 'FALLA ')+m)
with sync_playwright() as p:
    b=p.chromium.launch(args=['--no-proxy-server'])
    pg=b.new_page(viewport={'width':1280,'height':900});pg.on('pageerror',lambda e:errs.append(str(e)[:300]));pg.on('console',lambda m:errs.append(m.text[:200]) if m.type=='error' else None)
    pg.goto(B);pg.wait_for_timeout(2500);fr=pg.frame_locator('#pubframe')
    fr.locator('.hero img').dblclick();pg.wait_for_timeout(800)
    ok(pg.evaluate('location.hash')=='#acceso','doble clic en el logo abre el acceso del equipo')
    pg.wait_for_selector('#lu');pg.select_option('#lu','u1');pg.fill('#lp','1234');pg.click('[data-act=login]');pg.wait_for_timeout(1000)
    pg.evaluate("location.hash='#panel/config'");pg.wait_for_timeout(900)
    ok(pg.locator('.cfg-sec').count()>=4,'índice por secciones (%d)'%pg.locator('.cfg-sec').count())
    vis=lambda:pg.evaluate("[...document.querySelectorAll('.cfg-card')].filter(c=>!c.hidden).map(c=>c.querySelector('.cfg-ht b').textContent)")
    print('  Negocio:',vis());pg.screenshot(path='/tmp/cfg1.png')
    h=pg.evaluate("document.documentElement.scrollHeight");ok(h<2600,'altura de la pantalla %d px (antes ~6.500)'%h)
    pg.click('[data-cfgsec=caja]');pg.wait_for_timeout(300);print('  Caja:',vis())
    pg.fill('#cfg-q','fiado');pg.wait_for_timeout(300);r=vis();print('  busca fiado:',r);ok(len(r)>=1 and any('Fiado' in x for x in r),'buscador encuentra Fiado')
    pg.fill('#cfg-q','recargo tarjeta');pg.wait_for_timeout(300);print('  busca recargo tarjeta:',vis())
    pg.fill('#cfg-q','');pg.click('[data-cfgsec=negocio]');pg.wait_for_timeout(300)
    pg.fill('#cf-n','Di Parma Centro');pg.wait_for_timeout(300)
    ok(pg.locator('.cfg-card.dirty').count()==1,'marca cambios sin guardar');print('  índice:',pg.inner_text('[data-cfgn=negocio]'))
    pg.click('[data-act=cfgSave]');pg.wait_for_timeout(900)
    ok(pg.evaluate("S.tenant.name")=='Di Parma Centro','Guardar sigue funcionando (núcleo)');ok(pg.locator('.cfg-card.dirty').count()==0,'se limpia la marca');ok(pg.locator('.cfg-sec.on').get_attribute('data-cfgsec')=='negocio','queda en la misma sección')
    pg.keyboard.press('/');ok(pg.evaluate("document.activeElement.id")=='cfg-q','tecla / va al buscador')
    pg.set_viewport_size({'width':360,'height':800});pg.wait_for_timeout(400);ok(pg.evaluate("document.documentElement.scrollWidth-document.documentElement.clientWidth")<=1,'sin desborde a 360 px');pg.screenshot(path='/tmp/cfg2.png')
    m=b.new_page(viewport={'width':390,'height':800},has_touch=True,is_mobile=True);m.goto(B);m.wait_for_timeout(2500)
    img=m.frame_locator('#pubframe').locator('.hero img');img.tap();m.wait_for_timeout(120);img.tap();m.wait_for_timeout(800)
    ok(m.evaluate('location.hash')=='#acceso','doble toque en el celular abre el acceso')
    print('\n'.join(errs) or 'sin errores');b.close()
